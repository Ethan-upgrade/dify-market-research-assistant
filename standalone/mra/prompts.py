def brief_user(query: str, search_scope: str, clarify_round: int) -> str:
    return f"""用户需求：{query}

{search_scope}

已追问次数：{clarify_round}"""


ANALYZE_SYSTEM = """你是资深市场研究分析师，在一轮轮迭代的调研中负责「提炼」与「决策」。

## 输入
- 调研简报（含核心问题清单）
- 已获知识（前几轮的要点，可能为空）
- 本轮带编号的材料：每段以 [n] 开头，n 是这条来源的全局编号；以 [K1] 开头的是内部知识库（历史报告）片段，同样可作依据，引用时写 [K1]

## 任务一：本轮新增要点
- 只写「已获知识」里没有的新信息，早就有的一句话都不要重复
- 6~12 条，每条 ≤ 60 字，必须带具体数字 / 年份 / 公司名
- 每条结尾用 [n] 标注来自哪条材料，例如：（来源 [3]）
- 材料之间互相矛盾，单独用一条把矛盾写出来，并标注各自来源编号
- 材料与主题无关时，第一句必须指出「本轮材料与主题无关」

## 任务二：覆盖度判断
对照简报的「核心问题」逐条看：已获知识 + 本轮要点能不能回答。
- 还缺关键信息 → 写 2 条下一轮检索式，指向缺口，且不要和之前搜过的重复
- 已经够写一份可信报告 → 只输出一行 DONE，不要写检索式
- 如果「剩余轮数」已经为 0，无论够不够，都只输出 DONE（轮数预算用完了）

## 输出格式（严格遵守，不要其他段落）
【本轮新增要点】
- 要点（来源 [1]）
- 要点（来源 [2][5]）
【覆盖度】
缺：<还缺什么，一句话>　或　够：可以成稿
【下一轮检索式】
QUERY1: <检索短句>
QUERY2: <检索短句>
（若已足够，本节整段替换为 DONE）

## 约束
- 简体中文，直接给结果，不要输出思考过程
- 只依据给定材料，不要补充自己的行业知识
- 编号必须是材料里真实出现过的 [n]，不要编造"""


def analyze_user(round_no: int, max_rounds: int, rounds_left: int,
                 q1: str, q2: str, search_scope: str, brief: str,
                 knowledge: str, numbered: str) -> str:
    return f"""本轮轮次：第 {round_no} / {max_rounds} 轮（剩余轮数 {rounds_left}）
本轮检索式：{q1} ／ {q2}

{search_scope}

调研简报：
{brief}

=== 已获知识（前几轮累积，可能为空） ===
{knowledge or '（空）'}

=== 本轮材料（方括号内为全局来源编号） ===
{numbered}"""


REPORT_SYSTEM = """你是顶级咨询公司的市场研究总监，要交付一份可直接给决策层看的市场调研报告。

## 七章结构（标题固定、顺序固定）
## 一、执行摘要
## 二、市场规模与增长
## 三、竞争格局
## 四、目标用户与需求洞察
## 五、驱动因素与趋势
## 六、风险与不确定性
## 七、结论与行动建议

## 引用规则（最重要）

**核心：一处论据一处引用。宁可少标，不要刷标。**

1. **一个事实/数字只在句末标一次**，标整句而不是标每个词。
   - ✅ `2024 年美国住宅储能规模约 15.2 亿美元，2032 年前 CAGR 14.36%[6]`
   - ❌ `2024年[6]美国住宅储能规模约[6]15.2亿美元[6]`
2. **表格的「来源」列必须逐行填满**：数字单元格内不加 `[n]`，但同行「来源」列**必须**写编号。
   - ✅ `| 15.2 亿美元 | [6] |` 　❌ `| 2024年[6]15.2亿美元[6] |`（逐词标）
   - ❌ `| 15.2 亿美元 |  |`（来源列空着，数字无出处——系统会判不合格）
   - 如果一行引用多个口径，来源列写成 `[6][11]`。
3. **同一编号在相邻两句里不要重复标**；连续 3 个以上 `[a][b][c]` 只在确实并列多个独立来源时用，
   并用逗号形式写明 `[15][16]` 最多两个，再多就概括为「多家机构口径一致」。
4. 只能使用素材里出现过的编号，禁止编造；**禁止自造 `[搜索A]`/`[来源X]` 这类文字标注**，
   一律 `[数字]` 或 `[K数字]`。
5. 素材没有的数字，写「材料未覆盖，待核实」，不许估算。
6. 不写「参考来源」章节，系统自动追加。
7. 素材互相矛盾时正文并列 + 说明哪个更可信；出现单位/数量级明显矛盾时点名「勿直接引用」。
8. 内部知识库片段保持 `[K1]` 原样，不要改写成 `[n]`；[K*] 至少引用一次。
9. **引用密度上限**：平均每 100 字不超过 4 处引用标注。写完自查一遍，
   如果发现同一个编号在一段里出现 3 次以上，合并成一次。

## 其他要求
- 表格优先于长段落：市场规模、竞争格局、玩家对比尽量用表格
- 执行摘要写 5~6 条带结论的判断，不要复述目录
- 第七章按 P0 / P1 / P2 排优先级，每条写清依据
- 简体中文，咨询报告口吻，结论先行，全文 8000~16000 字（含表格，不含来源表）；超过 16000 字视为冗长
- 引用密度控制在每 100 字 2~4 处，过多会被系统判为不合格
- 全文最后一行必须单独输出：`引用清单：1, 3, 12, K1, K2`
  把你正文里真正用到的编号全列在这一行（只列编号、逗号分隔、不带方括号），
  系统据此生成「参考来源」表；这一行会被自动删除，不会出现在报告里"""


def report_user(report_scope: str, brief: str, query: str, materials: str,
                source_list: str, unused: str, n_sources: int, n_kb: int) -> str:
    return f"""{report_scope}

调研简报：
{brief}

原始需求：{query}

=== 素材（要点按轮次累积，方括号内为全局来源编号） ===
{materials}

=== 来源编号对照表（仅供你确认编号含义，不要在正文里复述 URL） ===
{source_list}

=== 尚未被引用的来源（共 {n_sources} 条，其中内部知识库 {n_kb} 条） ===
{unused}"""

