def _key(v: str) -> str:
    return (v or "").strip().lower().replace(" ", "").replace("　", "")


def normalize(value: str, options: list, aliases: dict, field: str) -> str:
    """把用户输入映射成 options 里的某一项；映射不了抛 ValueError。"""
    raw = (value or "").strip()
    if not raw:
        return options[0]

    # 1) 精确
    for opt in options:
        if raw == opt:
            return opt

    # 2) 别名表（大小写/空格归一）
    k = _key(raw)
    for alias, target in aliases.items():
        if _key(alias) == k:
            return target

    # 3) 子串：用户写「德语教育」→ 命中「教育」
    for alias, target in sorted(aliases.items(), key=lambda x: -len(x[0])):
        if _key(alias) and _key(alias) in k:
            return target

    raise ValueError(f"{field} 不认识「{raw}」，可选：{'、'.join(options)}")
